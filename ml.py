from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.svm import SVC

# Veri kümesini yükle
iris = load_iris()

# Veriyi eğitim+doğrulama ve test olarak ayır
X_trainval, X_test, y_trainval, y_test = train_test_split(
    iris.data, iris.target, random_state=0)

# Eğitim+doğrulama verisini tekrar eğitim ve doğrulama olarak ayır
X_train, X_valid, y_train, y_valid = train_test_split(
    X_trainval, y_trainval, random_state=1)

# Küme büyüklüklerini yazdır
print("Eğitim kümesi boyutu: {}, Doğrulama kümesi boyutu: {}, Test kümesi boyutu: {}\n"
      .format(X_train.shape[0], X_valid.shape[0], X_test.shape[0]))

# En iyi modeli takip etmek için skor ve parametre tut
best_score = 0
best_parameters = {'gamma': None, 'C': None}

# Hiperparametre arama döngüsü
for gamma in [0.001, 0.01, 0.1, 1, 10, 100]:
    for C in [0.001, 0.01, 0.1, 1, 10, 100]:
        # Modeli eğit
        svm = SVC(gamma=gamma, C=C)
        svm.fit(X_train, y_train)

        # Doğrulama kümesi üzerinde değerlendir
        score = svm.score(X_valid, y_valid)

        # En iyi skoru güncelle
        if score > best_score:
            best_score = score
            best_parameters['gamma'] = gamma
            best_parameters['C'] = C

# En iyi parametrelerle tüm eğitim+doğrulama verisiyle modeli eğit
svm = SVC(**best_parameters)
svm.fit(X_trainval, y_trainval)

# Test kümesi üzerinde başarıyı değerlendir
test_score = svm.score(X_test, y_test)

print("En iyi doğrulama skoru: {:.2f}".format(best_score))
print("En iyi parametreler: gamma = {}, C = {}".format(best_parameters['gamma'], best_parameters['C']))
print("Test kümesi üzerindeki başarı: {:.2f}".format(test_score))

svm = SVC(**best_parameters)
svm.fit(X_trainval, y_trainval)
test_score = svm.score(X_test, y_test)
print("Best score on validation set: {:.2f}".format(best_score))
print("Best parameters: ", best_parameters)
print("Test set score with best parameters: {:.2f}".format(test_score))
from sklearn.datasets import load_breast_cancer
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import classification_report

# Meme kanseri veri setini yükleyelim
data = load_breast_cancer()
X = data.data
y = data.target

# Veriyi eğitim ve test setlerine ayıralım
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

# Veriyi standartlaştırma (MLP modelleri için çok önemlidir)
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# MLPClassifier için hiperparametreler
param_grid = {
    'hidden_layer_sizes': [(50,), (100,), (100, 100), (100, 100, 100)],  # Farklı gizli katman yapıları
    'activation': ['relu', 'tanh', 'logistic'],  # Aktivasyon fonksiyonları
    'solver': ['adam', 'sgd', 'lbfgs'],  # Çözümleyiciler
    'alpha': [0.0001, 0.001, 0.01, 0.1],  # Düzenleme parametresi
    'learning_rate': ['constant', 'invscaling', 'adaptive'],  # Öğrenme oranı stratejisi
    'max_iter': [200, 300, 500],  # Maksimum iterasyon sayısı
}

# GridSearchCV kullanarak hiperparametre optimizasyonu yapalım
grid_search = GridSearchCV(MLPClassifier(random_state=42), param_grid, cv=5, n_jobs=-1, verbose=1)
grid_search.fit(X_train, y_train)

# En iyi hiperparametreler ve performans
print("En iyi hiperparametreler:", grid_search.best_params_)
print("En iyi skor:", grid_search.best_score_)

# Test seti ile modelin değerlendirilmesi
best_model = grid_search.best_estimator_
y_pred = best_model.predict(X_test)

# Sonuçların değerlendirilmesi
print("\nTest Sonuçları:")
print(classification_report(y_test, y_pred))

# Sonuçları görselleştirebiliriz
plt.figure(figsize=(8, 6))
plt.title("Hiperparametre Performans Karşılaştırması")
plt.bar(grid_search.cv_results_['params'], grid_search.cv_results_['mean_test_score'])
plt.xticks(rotation=90)
plt.xlabel("Parametre Kombinasyonu")
plt.ylabel("Ortalama Test Skoru")
plt.show()

